"""
pipeline/rbac.py

Role-Based Access Control for persona-filtered API responses.

Personas:
  - gm:
      Full business access including revenue, PVM decomposition,
      confidence, evidence, root causes, and action recommendations.

  - ops_lead:
      Operational access only. No revenue, PVM financial decomposition,
      financial impact, or raw confidence scores.

  - analyst:
      Full analytical access including raw scores, graph topology,
      correlation matrix, and PVM decomposition.

RBAC is applied at the RESPONSE layer:
    full pipeline result
            ↓
        RBAC filter
            ↓
      persona-specific response

The underlying pipeline always runs using the complete dataset.
RBAC does not modify the underlying investigation result.
"""

