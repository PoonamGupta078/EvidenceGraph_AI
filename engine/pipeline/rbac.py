def _filter_kpi_mapping(
    mapping: Dict[str, Any],
    allowed_kpis: List[str],
) -> Dict[str, Any]:
    """
    Keep only KPI keys explicitly allowed for the persona.
    """
    if not isinstance(mapping, dict):
        return {}

    return {
        key: value
        for key, value in mapping.items()
        if key in allowed_kpis
    }


def _filter_root_causes(
    root_causes: Any,
    persona: Dict[str, Any],
) -> List[Dict[str, Any]]:
    """
    Filter root-cause candidates according to persona permissions.

    PVM contribution nodes are allowed only for personas with PVM access.
    """

    if not isinstance(root_causes, list):
        return []

    allowed_kpis = set(persona["allowed_kpis"])
    can_see_pvm = persona["can_see_pvm"]
    can_see_raw_scores = persona["can_see_raw_scores"]

    filtered = []

    for root_cause in root_causes:

        if not isinstance(root_cause, dict):
            continue

        kpi = root_cause.get("kpi")

        if not isinstance(kpi, str):
            continue

        # Normal KPI permission.
        allowed = kpi in allowed_kpis

        # PVM contribution-node permission.
        if kpi in PVM_NODES:
            allowed = can_see_pvm

        if not allowed:
            continue

        item = dict(root_cause)

        # Remove internal/raw scoring information for restricted personas.
        if not can_see_raw_scores:
            item.pop("graph_score", None)
            item.pop("composite_score", None)
            item.pop("evidence_score", None)

            # These may contain numerical impact information.
            item.pop("normalized_impact", None)
            item.pop("effect_size", None)
            item.pop("impact_score", None)

        # Financial PVM contribution is hidden from non-financial personas.
        if not persona["can_see_financial_impact"]:
            item.pop("contribution_magnitude_usd", None)
            item.pop("contribution_score", None)

        filtered.append(item)

    return filtered


def _filter_causal_chain(
    causal_chain: Any,
    persona: Dict[str, Any],
) -> List[str]:
    """
    Filter causal-chain nodes according to persona permissions.

    PVM nodes are retained only when the persona has PVM access.
    """

    if not isinstance(causal_chain, list):
        return []

    allowed_kpis = set(persona["allowed_kpis"])
    can_see_pvm = persona["can_see_pvm"]

    result = []

    for kpi in causal_chain:

        if not isinstance(kpi, str):
            continue

        if kpi in PVM_NODES:
            if can_see_pvm:
                result.append(kpi)
        elif kpi in allowed_kpis:
            result.append(kpi)

    return result


def _filter_evidence_graph(
    evidence_graph: Dict[str, Any],
    persona: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Filter Evidence Graph nodes and links.

    The graph topology itself is available to personas with
    can_see_graph_topology=True.

    Financial/PVM nodes remain hidden when PVM access is disabled.
    """

    if not isinstance(evidence_graph, dict):
        return {}

    if not persona["can_see_graph_topology"]:
        return {}

    allowed_kpis = set(persona["allowed_kpis"])
    can_see_pvm = persona["can_see_pvm"]

    def node_allowed(node_id: str) -> bool:
        if node_id in PVM_NODES:
            return can_see_pvm

        return node_id in allowed_kpis

    graph_data = evidence_graph.get("graph_data", {})

    raw_nodes = graph_data.get("nodes", [])
    raw_links = graph_data.get("links", [])

    nodes = []
    for node in raw_nodes:

        if not isinstance(node, dict):
            continue

        node_id = node.get("id")

        if not isinstance(node_id, str):
            continue

        if not node_allowed(node_id):
            continue

        filtered_node = dict(node)

        # Restrict raw centrality information for ops_lead.
        if not persona["can_see_raw_scores"]:
            filtered_node.pop("centrality", None)

        nodes.append(filtered_node)

    allowed_node_ids = {
        node.get("id")
        for node in nodes
        if isinstance(node, dict)
    }

    links = []

    for link in raw_links:

        if not isinstance(link, dict):
            continue

        source = link.get("source")
        target = link.get("target")

        if (
            source not in allowed_node_ids
            or target not in allowed_node_ids
        ):
            continue

        filtered_link = dict(link)

        # Raw graph weights/correlations are analytical information.
        if not persona["can_see_raw_scores"]:
            filtered_link.pop("weight", None)
            filtered_link.pop("correlation", None)

        links.append(filtered_link)

    # Driver ranking.
    driver_ranking = []

    for ranking in evidence_graph.get("driver_ranking", []):

        if not isinstance(ranking, dict):
            continue

        kpi = ranking.get("kpi")

        if not isinstance(kpi, str):
            continue

        if not node_allowed(kpi):
            continue

        item = dict(ranking)

        if not persona["can_see_raw_scores"]:
            item.pop("score", None)

        driver_ranking.append(item)

    result = {
        "nodes": nodes,
        "links": links,
        "driver_ranking": driver_ranking,
    }

    # Analyst can see the graph's detailed correlation matrix.
    if persona["can_see_raw_scores"]:
        result["correlation_matrix"] = _filter_correlation_matrix(
            evidence_graph.get("correlation_matrix", {}),
            persona,
        )

    return result


def _filter_correlation_matrix(
    correlation_matrix: Any,
    persona: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Filter correlation pairs so that restricted KPI/PVM information
    does not leak to the persona.
    """

    if not isinstance(correlation_matrix, dict):
        return {}

    allowed_kpis = set(persona["allowed_kpis"])
    can_see_pvm = persona["can_see_pvm"]

    def allowed_node(node: str) -> bool:
        if node in PVM_NODES:
            return can_see_pvm

        return node in allowed_kpis

    filtered = {}

    for pair, value in correlation_matrix.items():

        if not isinstance(pair, str):
            continue

        # Evidence Graph uses "source→target".
        if "→" not in pair:
            continue

        source, target = pair.split("→", 1)

        if allowed_node(source) and allowed_node(target):
            filtered[pair] = value

    return filtered


