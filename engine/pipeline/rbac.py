def get_personas() -> List[Dict[str, Any]]:
    """
    Returns persona definitions for the /personas endpoint.

    Internal permission fields are included because this endpoint is
    intended for the application's persona configuration/UI.
    """

    return [
        {
            "id": persona_id,
            **{
                key: value
                for key, value in definition.items()
            },
        }
        for persona_id, definition in PERSONA_DEFINITIONS.items()
    ]


def filter_for_persona(
    investigation_result: Dict[str, Any],
    persona_id: str,
) -> Dict[str, Any]:
    """
    Filter a complete investigation result for a specific persona.

    Args:
        investigation_result:
            Full pipeline result before RBAC filtering.

        persona_id:
            "gm", "ops_lead", or "analyst".

    Returns:
        Persona-specific investigation result.

    Security behavior:
        Unknown personas default to the most restrictive persona
        (ops_lead).

    Important:
        This function never mutates investigation_result.
    """

    if not isinstance(investigation_result, dict):
        raise TypeError(
            "investigation_result must be a dictionary."
        )

    persona = PERSONA_DEFINITIONS.get(persona_id)

    if persona is None:
        # Fail closed.
        persona_id = "ops_lead"
        persona = PERSONA_DEFINITIONS["ops_lead"]

    filtered: Dict[str, Any] = {}

    # -----------------------------------------------------------------------
    # Base investigation metadata
    # -----------------------------------------------------------------------

    for field in [
        "region_id",
        "scenario",
        "investigation_id",
        "timestamp",
    ]:
        if field in investigation_result:
            filtered[field] = investigation_result[field]

    # -----------------------------------------------------------------------
    # KPI health
    # -----------------------------------------------------------------------

    if "kpi_health" in investigation_result:
        filtered["kpi_health"] = _filter_kpi_mapping(
            investigation_result["kpi_health"],
            persona["allowed_kpis"],
        )

    # -----------------------------------------------------------------------
    # Materiality
    # -----------------------------------------------------------------------

    if "materiality" in investigation_result:

        materiality = investigation_result["materiality"]

        if isinstance(materiality, dict):

            allowed = set(persona["allowed_kpis"])

            filtered_materiality = {
                "material_kpis": [
                    k
                    for k in materiality.get("material_kpis", [])
                    if k in allowed
                ],
                "any_material": materiality.get(
                    "any_material",
                    False,
                ),
                "signal_strength": materiality.get(
                    "signal_strength"
                ),
                "kpi_results": {
                    k: v
                    for k, v in materiality.get(
                        "kpi_results",
                        {},
                    ).items()
                    if k in allowed
                },
            }

            filtered["materiality"] = filtered_materiality

    # -----------------------------------------------------------------------
    # Confidence
    # -----------------------------------------------------------------------

    if "confidence" in investigation_result:

        confidence = investigation_result["confidence"]

        if isinstance(confidence, dict):

            filtered_confidence = {
                "verdict": confidence.get("verdict"),
                "explanation": confidence.get("explanation"),
            }

            if persona["can_see_raw_scores"]:

                filtered_confidence["score"] = confidence.get(
                    "score"
                )

                filtered_confidence["sub_scores"] = confidence.get(
                    "sub_scores"
                )

                filtered_confidence["weights"] = confidence.get(
                    "weights"
                )

            filtered["confidence"] = filtered_confidence

    # -----------------------------------------------------------------------
    # Verdict
    # -----------------------------------------------------------------------

    if "verdict" in investigation_result:
        filtered["verdict"] = investigation_result["verdict"]

    # -----------------------------------------------------------------------
    # Primary cause
    # -----------------------------------------------------------------------

    if "primary_cause" in investigation_result:
        primary_cause = investigation_result["primary_cause"]
        if isinstance(primary_cause, dict):
            kpi = primary_cause.get("kpi")
            if kpi in persona["allowed_kpis"] or (kpi in PVM_NODES and persona["can_see_pvm"]):
                filtered_pc = dict(primary_cause)
                if not persona["can_see_raw_scores"]:
                    filtered_pc.pop("graph_score", None)
                    filtered_pc.pop("composite_score", None)
                    filtered_pc.pop("evidence_score", None)
                    filtered_pc.pop("normalized_impact", None)
                    filtered_pc.pop("effect_size", None)
                    filtered_pc.pop("impact_score", None)
                if not persona["can_see_financial_impact"]:
                    filtered_pc.pop("contribution_magnitude_usd", None)
                    filtered_pc.pop("contribution_score", None)
                filtered["primary_cause"] = filtered_pc
        elif isinstance(primary_cause, str):
            if primary_cause in persona["allowed_kpis"] or (primary_cause in PVM_NODES and persona["can_see_pvm"]):
                filtered["primary_cause"] = primary_cause

    # -----------------------------------------------------------------------
    # Action recommendation
    # -----------------------------------------------------------------------

    if "action" in investigation_result:

        action = investigation_result["action"]

        if isinstance(action, dict):

            filtered_action = dict(action)

            if not persona["can_see_financial_impact"]:

                # Financial fields that must not reach ops_lead.
                for field in [
                    "estimated_impact",
                    "estimated_impact_usd",
                    "revenue_impact",
                    "revenue_recovery_estimate",
                    "financial_impact",
                    "contribution_magnitude_usd",
                ]:
                    filtered_action.pop(field, None)

            filtered["action"] = filtered_action

    # -----------------------------------------------------------------------
    # Root causes
    # -----------------------------------------------------------------------

    if (
        "root_causes" in investigation_result
        and "root_causes" in persona["allowed_fields"]
    ):
        filtered["root_causes"] = _filter_root_causes(
            investigation_result["root_causes"],
            persona,
        )

    # -----------------------------------------------------------------------
    # Evidence summary
    # -----------------------------------------------------------------------

    if (
        "evidence_summary" in investigation_result
        and "evidence_summary" in persona["allowed_fields"]
    ):
        filtered["evidence_summary"] = (
            investigation_result["evidence_summary"]
        )

    # -----------------------------------------------------------------------
    # Causal chain
    # -----------------------------------------------------------------------

    if (
        "causal_chain" in investigation_result
        and "causal_chain" in persona["allowed_fields"]
    ):
        filtered["causal_chain"] = _filter_causal_chain(
            investigation_result["causal_chain"],
            persona,
        )

    # Compatibility with root_cause.py's temporal_sequence.
    elif (
        "temporal_sequence" in investigation_result
        and "causal_chain" in persona["allowed_fields"]
    ):
        filtered["temporal_sequence"] = _filter_causal_chain(
            investigation_result["temporal_sequence"],
            persona,
        )

    # -----------------------------------------------------------------------
    # Challenge Engine
    # -----------------------------------------------------------------------

    if (
        "challenge_result" in investigation_result
        and (
            "challenge_result" in persona["allowed_fields"]
            or "challenge_summary" in persona["allowed_fields"]
        )
    ):
        filtered["challenge_result"] = (
            investigation_result["challenge_result"]
        )

    # -----------------------------------------------------------------------
    # Evidence Graph
    # -----------------------------------------------------------------------

    if "evidence_graph" in investigation_result:
        graph = _filter_evidence_graph(
            investigation_result["evidence_graph"],
            persona,
        )

        if graph:
            filtered["evidence_graph"] = graph

    # -----------------------------------------------------------------------
    # PVM decomposition
    # -----------------------------------------------------------------------

    if (
        "pvm_decomposition" in investigation_result
        and persona["can_see_pvm"]
        and persona["can_see_financial_impact"]
    ):
        filtered["pvm_decomposition"] = (
            investigation_result["pvm_decomposition"]
        )

    # -----------------------------------------------------------------------
    # Raw sub-scores
    # -----------------------------------------------------------------------

    if (
        persona["can_see_raw_scores"]
        and "raw_sub_scores" in investigation_result
        and "raw_sub_scores" in persona["allowed_fields"]
    ):
        filtered["raw_sub_scores"] = dict(
            investigation_result.get(
                "raw_sub_scores",
                {},
            )
        )

    # -----------------------------------------------------------------------
    # Correlation matrix
    # -----------------------------------------------------------------------

    if (
        persona["can_see_raw_scores"]
        and "correlation_matrix" in investigation_result
        and "correlation_matrix" in persona["allowed_fields"]
    ):
        filtered["correlation_matrix"] = _filter_correlation_matrix(
            investigation_result.get(
                "correlation_matrix",
                {},
            ),
            persona,
        )

    # -----------------------------------------------------------------------
    # Telemetry
    # -----------------------------------------------------------------------

    if "telemetry" in investigation_result:

        telemetry = investigation_result["telemetry"]

        if isinstance(telemetry, dict):

            # Telemetry is operational metadata rather than business KPI
            # data. Keep it available, but hide potentially sensitive
            # token/cost details from the operational persona.
            if persona_id == "ops_lead":

                safe_telemetry = dict(telemetry)

                for field in [
                    "token_count",
                    "input_tokens",
                    "output_tokens",
                    "total_tokens",
                    "cost",
                    "estimated_cost",
                    "llm_cost",
                ]:
                    safe_telemetry.pop(field, None)

                filtered["telemetry"] = safe_telemetry

            else:
                filtered["telemetry"] = dict(telemetry)

    # -----------------------------------------------------------------------
    # Persona context
    # -----------------------------------------------------------------------

    all_business_kpis = CORE_KPIS + PVM_KPIS

    filtered["persona_context"] = {
        "persona_id": persona_id,
        "label": persona["label"],
        "description": persona["description"],
        "color": persona["color"],

        "restricted_kpis_hidden": [
            kpi
            for kpi in all_business_kpis
            if kpi not in persona["allowed_kpis"]
        ],

        "pvm_access": persona["can_see_pvm"],
        "financial_impact_access": persona["can_see_financial_impact"],
        "raw_score_access": persona["can_see_raw_scores"],
        "graph_topology_access": persona["can_see_graph_topology"],
    }

    return filtered